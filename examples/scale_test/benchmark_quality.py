import os
import sys
import json
import asyncio
from typing import Dict

sys.path.append(os.path.join(os.path.dirname(__file__), "..", "..", "src"))
import os
from dotenv import load_dotenv
load_dotenv(os.path.join(os.path.dirname(__file__), "..", "..", ".env"))
from openai import OpenAI
from intentmind import IntentmindMemory

client = OpenAI()
model_name = os.getenv("OPENAI_MODEL")

TEST_QUERIES = [
    # Local Queries (Specific details)
    {"type": "Local", "query": "Who is Mr. Darcy's friend?"},
    {"type": "Local", "query": "What did Elizabeth Bennet think of Mr. Darcy at the first ball?"},
    
    # Global Queries (Synthesis across dataset)
    {"type": "Global", "query": "How do social class and wealth influence marriages in the story?"},
    {"type": "Global", "query": "Describe the overall progression of Elizabeth and Darcy's relationship."}
]

def generate_answer(query: str, context: str) -> str:
    prompt = f"""You are a helpful assistant answering questions based on the provided text context.
Answer directly and clearly. If the answer is not in the context, say so.

Context:
{context}

Question: {query}"""
    
    response = client.chat.completions.create(
        model=model_name,
        messages=[
            {"role": "system", "content": "You are a literary assistant."},
            {"role": "user", "content": prompt}
        ]
    )
    return response.choices[0].message.content

def evaluate_with_judge(query: str, intentmind_ans: str, baseline_ans: str) -> Dict:
    prompt = f"""You are an expert evaluator of RAG (Retrieval-Augmented Generation) systems.
You are given a user question and two answers generated by different AI systems using different retrieved contexts.

Evaluate which answer is better based on:
1. Relevance to the question
2. Comprehensiveness (especially for global synthesis questions)
3. Factual grounding in the context

User Question: {query}

[System A (Intentmind)]
{intentmind_ans}

[System B (Baseline RAG)]
{baseline_ans}

Decide which system wins. Reply in strict JSON format:
{{
    "winner": "System A" | "System B" | "Tie",
    "reasoning": "Explanation of why"
}}
"""
    response = client.chat.completions.create(
        model=model_name,
        messages=[
            {"role": "system", "content": "You are an impartial judge. Respond only in JSON format."},
            {"role": "user", "content": prompt}
        ],
        response_format={"type": "json_object"}
    )
    
    try:
        return json.loads(response.choices[0].message.content)
    except:
        return {"winner": "Error", "reasoning": "Failed to parse JSON."}

def main():
    print("Loading Intentmind Memory Engine for Quality Benchmark...")
    if os.path.exists("scale_test.json"):
        memory = IntentmindMemory.load("scale_test.json")
    else:
        memory = IntentmindMemory()
    
    nodes = memory._store.intents.values()
    if len(nodes) < 10:
        print("Warning: Graph is very small. Run bulk_ingest.py first for a realistic benchmark.")

    results = []
    
    for q in TEST_QUERIES:
        query_text = q["query"]
        q_type = q["type"]
        print(f"\n--- Testing {q_type} Query: '{query_text}' ---")
        
        # 1. Intentmind (Graph + Vector)
        print("Retrieving Intentmind Context...")
        im_result = memory.query(query_text)
        im_context = im_result["prompt"]
        im_answer = generate_answer(query_text, im_context)
        
        # 2. Baseline RAG (Vector Only)
        print("Retrieving Baseline RAG Context...")
        # Get query embedding
        query_emb = memory.embedder.embed(query_text)
        # Standard vector search (top 5)
        raw_chunks = [c for _, c in memory._store.search_chunks(query_emb, top_k=5)]
        baseline_context = "\n".join([f"- {c.text}" for c in raw_chunks])
        baseline_answer = generate_answer(query_text, baseline_context)
        
        # 3. AutoE (LLM as a judge)
        print("Evaluating...")
        evaluation = evaluate_with_judge(query_text, im_answer, baseline_answer)
        
        print(f"Winner: {evaluation['winner']}")
        print(f"Reasoning: {evaluation['reasoning']}")
        
        results.append({
            "query": query_text,
            "type": q_type,
            "winner": evaluation['winner']
        })

    print("\n=== Benchmark Summary ===")
    im_wins = sum(1 for r in results if r["winner"] == "System A")
    base_wins = sum(1 for r in results if r["winner"] == "System B")
    ties = sum(1 for r in results if r["winner"] == "Tie")
    
    print(f"Total Queries: {len(TEST_QUERIES)}")
    print(f"Intentmind (GraphRAG) Wins: {im_wins}")
    print(f"Baseline RAG Wins: {base_wins}")
    print(f"Ties: {ties}")

if __name__ == "__main__":
    main()
